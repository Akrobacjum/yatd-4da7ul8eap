import asyncio
from playwright.async_api import async_playwright
BASE='file:///tmp/claude-0/-home-claude/fb891867-3494-5a36-92d3-9beb0ec01e2f/scratchpad/test/page15.html'
OUT='/tmp/claude-0/-home-claude/fb891867-3494-5a36-92d3-9beb0ec01e2f/scratchpad/shots15/'
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); page = await (await b.new_context(viewport={'width':390,'height':844}, device_scale_factor=2)).new_page()
        errs=[]; page.on('pageerror', lambda e: errs.append(str(e)))
        await page.clock.install(); await page.goto(BASE); await page.clock.run_for(500)
        await page.click('#start-play'); await page.clock.run_for(400)
        while await page.evaluate("__yatd.modalKind"): await page.evaluate("__yatd.closeModal()")
        await page.evaluate("__yatd.run.unlocked.add('cage'); __yatd.run.unlocked.add('fire')")
        await page.click('#tab-traps'); await page.clock.run_for(200)
        await page.click('#item-cage'); await page.clock.run_for(200)
        print('cls', await page.evaluate("document.querySelector('#tray').className"))
        await page.screenshot(path=OUT+'tray_traps.png')
        geo = await page.evaluate("(() => { const t=document.querySelector('#tray'); const r=t.getBoundingClientRect(); const c=document.querySelector('#cv').getBoundingClientRect(); return { trayH: r.height, sw: t.scrollWidth, cw: t.clientWidth, sl: t.scrollLeft, canvasH: c.height, noHint: !document.querySelector('#hint'), toast: document.querySelector('#toast').hidden ? null : document.querySelector('#toast').innerText }; })()")
        print('geo', geo)
        await page.evaluate("document.querySelector('#tray').scrollLeft = 200"); await page.clock.run_for(200)
        await page.click('#tab-object'); await page.clock.run_for(200)
        print('object sl', await page.evaluate("document.querySelector('#tray').scrollLeft"))
        await page.evaluate("document.querySelector('#tray').scrollLeft = 120"); await page.clock.run_for(200)
        await page.click('#tab-traps'); await page.clock.run_for(200)
        print('traps sl back', await page.evaluate("document.querySelector('#tray').scrollLeft"))
        await page.click('#tab-object'); await page.clock.run_for(200)
        print('object sl back', await page.evaluate("document.querySelector('#tray').scrollLeft"))
        await page.click('#tab-deck'); await page.clock.run_for(200)
        await page.screenshot(path=OUT+'tray_deck.png')
        await page.click('#tab-object'); await page.clock.run_for(200)
        await page.click('#item-altar'); await page.clock.run_for(200)
        await page.screenshot(path=OUT+'tray_build.png')
        # Prototype 1.0: holding a tile shows what it does (and does not pick it); a tap still picks
        fails = []
        await page.click('#tab-traps'); await page.clock.run_for(200)
        await page.evaluate("document.querySelector('#tray').scrollLeft = 0"); await page.clock.run_for(200)
        box = await page.evaluate("(() => { const r = document.querySelector('#item-spikes').getBoundingClientRect(); return [r.left + r.width / 2, r.top + r.height / 2]; })()")
        sel0 = await page.evaluate("__yatd.selected")
        await page.mouse.move(box[0], box[1]); await page.mouse.down(); await page.clock.run_for(600)
        tip = await page.evaluate("(() => { const t = document.querySelector('#tip'); return { hidden: t.hidden, text: t.innerText, bottom: t.getBoundingClientRect().bottom, trayTop: document.querySelector('#drawer').getBoundingClientRect().top }; })()")
        await page.screenshot(path=OUT+'tray_hold.png')
        await page.mouse.up(); await page.clock.run_for(200)
        after = await page.evaluate("({ hidden: document.querySelector('#tip').hidden, sel: __yatd.selected })")
        desc = await page.evaluate("__yatd.ITEMS.spikes.desc")
        print('hold', tip, 'after', after, 'sel before', sel0)
        if tip['hidden'] or desc[:30] not in tip['text']: fails.append('tip shows the description')
        if tip['bottom'] > tip['trayTop']: fails.append('tip sits above the tray')
        if not after['hidden']: fails.append('tip hides on release')
        if after['sel'] != sel0: fails.append('a hold does not pick')
        await page.click('#item-spikes'); await page.clock.run_for(200)
        s1 = await page.evaluate("__yatd.selected")
        if s1 != 'spikes': fails.append('a tap picks: ' + str(s1))
        t1 = await page.evaluate("document.querySelector('#toast').hidden ? null : document.querySelector('#toast').innerText")
        print('toast after first pick', t1)
        await page.clock.run_for(10000)
        t2 = await page.evaluate("document.querySelector('#toast').hidden")
        if not t2: fails.append('toast goes away by itself')
        print('FAILS', fails)
        print('errs', errs[:3])
        await b.close()
asyncio.run(main())
